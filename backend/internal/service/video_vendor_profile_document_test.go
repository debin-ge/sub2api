func TestVideoVendorProfileDocumentMergeKeepsTierAPrecedence(t *testing.T) {
	tierA := map[string]*videoModelProfile{
		"vendor:model@1": {PublicModel: "vendor:model@1", MinSeconds: 1, MaxSeconds: 10, DefaultSeconds: 9},
	}
	document := vendorprofile.Document{Vendor: "runware", Profiles: []vendorprofile.Entry{
		{Model: "vendor:model@1", DefaultSeconds: 3},
		{Model: "Vendor:Model@2", MinSeconds: 4, MaxSeconds: 200, AllowsImage: true, Sizes: []string{"1920x1080", "bogus"}, AudioField: "settings.audio", Options: map[string]string{"seed": "seed", " ": "x"}},
		{Model: "vendor:model@3", Seconds: []int{0, 5, 10, 500}, Aspects: []string{"16:9", "9:16"}, Resolutions: []string{"720p"}, RequiresImage: true, AllowsImage: true, MaxImages: 2, SizeEnc: "resolution_only", Endpoint: "custom/path"},
		{Model: "   "},
	}}
	merged := mergeVideoVendorProfiles(tierA, document, videoVendorProfileDefaults{
		DurationEnc: videoDurationInt, SizeEnc: videoSizeWidthHeight, OutputPath: "videoURL", ImageField: "image_url", LastImageField: "end_image_url", EndpointIsID: true,
	})
	require.Len(t, merged, 3)
	require.Equal(t, 9, merged["vendor:model@1"].DefaultSeconds, "tier A wins over the generated entry")

	second := merged["vendor:model@2"]
	require.NotNil(t, second)
	require.Equal(t, 4, second.MinSeconds)
	require.Equal(t, videoVendorProfileMaxSeconds, second.MaxSeconds, "ranges are clamped to the catalog limit")
	require.Equal(t, 4, second.DefaultSeconds)
	require.Equal(t, []string{"1920x1080"}, second.Sizes, "unparseable sizes are dropped")
	require.Equal(t, "1920x1080", second.DefaultSize)
	require.True(t, second.AllowsImage)
	require.False(t, second.RequiresImage)
	require.Equal(t, 1, second.MaxImages)
	require.Equal(t, "settings.audio", second.AudioField)
	// seed 是 Ark 显式字段：finalizeArkDimensions 把它从白名单挪进 ArkFieldMap。
	require.Empty(t, second.OptionWhitelist)
	require.Equal(t, map[string]string{"seed": "seed"}, second.ArkFieldMap)
	require.Equal(t, []string{"16:9"}, second.Ratios)
	require.Equal(t, []string{"1080p"}, second.CanonicalResolutions)
	require.Equal(t, "16:9", second.DefaultRatio)
	require.Equal(t, "1080p", second.DefaultResolution)
	require.Equal(t, videoSizeWidthHeight, second.SizeEnc)
	require.Equal(t, "vendor:model@2", second.Endpoint, "endpoint defaults to the model id when the vendor submits by path")
	require.Equal(t, "image_url", second.ImageField)
	require.Equal(t, "videoURL", second.OutputPath)

	third := merged["vendor:model@3"]
	require.NotNil(t, third)
	require.Equal(t, []int{5, 10}, third.Seconds, "out-of-range enum values are dropped")
	require.Equal(t, 5, third.DefaultSeconds)
	require.Equal(t, []string{"1280x720", "720x1280"}, third.Sizes, "aspects × resolutions expand through the canonical table")
	require.True(t, third.RequiresImage)
	require.Equal(t, 2, third.MaxImages)
	require.Equal(t, videoSizeResolutionOnly, third.SizeEnc)
	require.Equal(t, "custom/path", third.Endpoint)
	require.NoError(t, validateVideoCapabilities("runware", videoVendorCapabilitiesFromProfiles("vendor:model@1", merged, map[VideoCapability]bool{VideoCapabilityCreate: true})))
}

func TestVideoVendorProfileDocumentDecodeRejectsForeignVendor(t *testing.T) {
	document := decodeVideoVendorProfileDocument([]byte(`{"vendor":"wavespeed","profiles":[{"model":"x"}]}`), "runware")
	require.Equal(t, "runware", document.Vendor)
	require.Empty(t, document.Profiles)
	document = decodeVideoVendorProfileDocument([]byte(`not json`), "runware")
	require.Empty(t, document.Profiles)
	document = decodeVideoVendorProfileDocument([]byte(`{"vendor":"runware","profiles":[{"model":"a:b@1","min_seconds":4,"max_seconds":8}]}`), "runware")
	require.Len(t, document.Profiles, 1)
}

func TestEmbeddedVendorProfilesLoadAndValidate(t *testing.T) {
	for _, vendor := range []string{VideoProviderRunware, VideoProviderWaveSpeed, VideoProviderFal} {
		document := loadVideoVendorProfileDocument(vendor)
		require.Equal(t, vendor, document.Vendor)
		adapter := videoVendorAdapterByName(vendor)
		require.NotNil(t, adapter)
		capabilities := adapter.DefaultCapabilities()
		require.NoError(t, validateVideoCapabilities(vendor, capabilities), vendor)
		for _, entry := range document.Profiles {
			require.True(t, capabilities.SupportedModels[entry.Model], "%s: generated model %s must be in the capability snapshot", vendor, entry.Model)
		}
	}
	// Runware 的生成档案必须覆盖 Tier A 之外的长尾模型，且不能覆盖 Tier A 的手写条目。
	runware := loadVideoVendorProfileDocument(VideoProviderRunware)
	require.NotEmpty(t, runware.Profiles, "runware.json must be generated by cmd/tools/video-vendor-profiles")
	profiles := runwareVideoProfiles()
	require.Equal(t, 5, profiles["bytedance:seedance@2.0"].DefaultSeconds)
	require.Contains(t, profiles["bytedance:seedance@2.0"].Sizes, "3840x2160")
	seen := map[string]bool{}
	for _, entry := range runware.Profiles {
		require.False(t, seen[entry.Model], "duplicate generated model %s", entry.Model)
		seen[entry.Model] = true
		require.NotNil(t, profiles[entry.Model])
	}
}
